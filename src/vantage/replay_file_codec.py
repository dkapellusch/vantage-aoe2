@dataclass(frozen=True, slots=True)
class ReplayFileCodecProfile:
    """Explicit180h coherent logical local seed, excluding cookie/save areas.

    HOME5/6/7 are supplied separately as addresses, never scalar snapshots.
    Physical adjacency between those homes and this frame is not inferred.
    Aliases admitted by the caller must share actual current Storage backing.
    No instruction-step cap replaces source loops. This sequential profile
    admits finite terminating accesses/child calls; native faults, EH, cookie,
    concurrency, executable-code mutation and physical registers are excluded.
    """

    frame: bytes

    def __post_init__(self) -> None:
        if type(self.frame) is not bytes or len(self.frame) != 0x180:
            raise ValueError("explicit180-hex-byte inner codec local seed required")


def _mask(bits: int) -> int:
    return (1 << bits) - 1


@dataclass(slots=True)
class _Word:
    value: int = 0
    known: int = 0


@dataclass(slots=True)
class _Registers:
    words: dict[str, _Word] = field(default_factory=dict)
    opaque_rax: int | None = None
    has_opaque_rax: bool = False

    def read(self, register: str, bits: int, site: int) -> int:
        word = self.words.get(register, _Word())
        mask = _mask(bits)
        if word.known & mask != mask:
            raise UnresolvedReplayTaskRebuild(
                f"codec{site:x} consumes undefined {register}/{bits}-bit value"
            )
        return word.value & mask

    def write(self, register: str, bits: int, value: int) -> None:
        mask = _mask(bits)
        if bits == 32:
            # Every source DWORD register write zero-extends its GPR.
            self.words[register] = _Word(value & mask, _U64)
        elif bits in (64, 128):
            self.words[register] = _Word(value & mask, mask)
        else:
            previous = self.words.get(register, _Word())
            self.words[register] = _Word(
                (previous.value & ~mask) | (value & mask), previous.known | mask
            )
        if register == "rax":
            self.opaque_rax, self.has_opaque_rax = None, False

    def imported_return(self, value: int | None) -> None:
        # Only nonvolatile registers survive the mandatory external capability.
        for register in ("rax", "rcx", "rdx", "r8", "r9", "r10", "r11", "xmm0"):
            self.words.pop(register, None)
        if type(value) is int and 0 <= value <= _U64:
            self.write("rax", 64, value)
        else:
            # No validation of an ignored return. Refuse only if later consumed.
            self.opaque_rax, self.has_opaque_rax = value, True

    def return_rax(self) -> int | None:
        word = self.words.get("rax", _Word())
        if word.known & _U64 == _U64:
            return word.value & _U64
        return self.opaque_rax if self.has_opaque_rax else None


@dataclass(slots=True)
class _Flags:
    carry: bool | None = None
    zero: bool | None = None
    sign: bool | None = None
    overflow: bool | None = None

    def invalidate(self) -> None:
        self.carry = self.zero = self.sign = self.overflow = None

    def require(self, name: str, site: int) -> bool:
        value = getattr(self, name)
        if value is None:
            raise UnresolvedReplayTaskRebuild(f"codec{site:x} consumes undefined {name} flag")
        return bool(value)

    def condition(self, code: str, site: int) -> bool:
        if code in ("e", "ne"):
            value = self.require("zero", site)
            return value if code == "e" else not value
        if code in ("s", "ns"):
            value = self.require("sign", site)
            return value if code == "s" else not value
        if code in ("b", "ae"):
            value = self.require("carry", site)
            return value if code == "b" else not value
        if code == "a":
            return not self.require("carry", site) and not self.require("zero", site)
        if code == "be":
            return self.require("carry", site) or self.require("zero", site)
        if code in ("l", "ge"):
            value = self.require("sign", site) != self.require("overflow", site)
            return value if code == "l" else not value
        raise UnresolvedReplayTaskRebuild(f"codec{site:x} has unprovided condition {code}")

    def logical(self, value: int, bits: int) -> None:
        self.zero, self.sign = value == 0, bool(value & (1 << (bits - 1)))
        self.carry = self.overflow = False

    def arithmetic(self, left: int, right: int, bits: int, *, subtract: bool) -> int:
        mask, high = _mask(bits), 1 << (bits - 1)
        result = (left - right if subtract else left + right) & mask
        self.zero, self.sign = result == 0, bool(result & high)
        self.carry = left < right if subtract else left + right > mask
        self.overflow = bool(
            ((left ^ right) if subtract else ~(left ^ right)) & (left ^ result) & high
        )
        return result


@dataclass(slots=True)
class _Machine:
    context: ReplayTaskRebuildStorage
    imports: ReplayTaskRebuildCalls
    homes: tuple[int, ...]
    registers: _Registers = field(default_factory=_Registers)
    flags: _Flags = field(default_factory=_Flags)
    site: int = 0

    def width(self, operand: _Operand) -> int:
        if operand[0] == "r":
            return operand[2]
        if operand[0] in ("m", "h"):
            return operand[1]
        raise UnresolvedReplayTaskRebuild(f"codec{self.site:x} has no immediate width")

    def address(self, operand: _Operand) -> int:
        if operand[0] == "h":
            return self.homes[operand[2]]
        if operand[0] == "m":
            value = operand[3]
            for register, scale in operand[2]:
                value += self.registers.read(register, 64, self.site) * scale
            return value & _U64
        raise UnresolvedReplayTaskRebuild(f"codec{self.site:x} requires memory address")

    def get(self, operand: _Operand, *, bits: int | None = None) -> int:
        if operand[0] == "i":
            return operand[1] if bits is None else operand[1] & _mask(bits)
        width = self.width(operand) if bits is None else bits
        if operand[0] == "r":
            return self.registers.read(operand[1], width, self.site)
        return _read(self.context, self.address(operand), width // 8)

    def put(self, operand: _Operand, value: int) -> None:
        width = self.width(operand)
        if operand[0] == "r":
            self.registers.write(operand[1], width, value)
        elif operand[0] in ("m", "h"):
            _write(self.context, self.address(operand), width // 8, value)
        else:
            raise UnresolvedReplayTaskRebuild(f"codec{self.site:x} writes an immediate")

    def imported(self, thunk: int) -> int | None:
        # Source argument registers are already held before the thunk's IAT read.
        args = tuple(self.registers.read(name, 64, self.site) for name in ("rcx", "rdx", "r8"))
        target = _read(self.context, _IATS[thunk], 8)
        if self.imports.call is None:
            raise UnresolvedReplayTaskRebuild(f"codec{self.site:x} import{target:x} unavailable")
        returned = self.imports.call(target, args, None)
        self.registers.imported_return(returned)
        self.flags.invalidate()
        return returned

    def binary(self, operation: str, destination: _Operand, source: _Operand) -> None:
        bits = self.width(destination)
        # XOR r,r is a source zero idiom, not a read of an uninitialized register.
        if operation == "xor" and destination == source and destination[0] == "r":
            left = right = 0
        else:
            left, right = self.get(destination), self.get(source, bits=bits)
        if operation in ("add", "sub", "cmp"):
            value = self.flags.arithmetic(left, right, bits, subtract=operation != "add")
        else:
            if operation in ("and", "test"):
                value = left & right
            elif operation == "or":
                value = left | right
            elif operation == "xor":
                value = left ^ right
            else:
                raise UnresolvedReplayTaskRebuild(f"codec{self.site:x} binary {operation}")
            value &= _mask(bits)
            self.flags.logical(value, bits)
        if operation not in ("cmp", "test"):
            self.put(destination, value)

    def shift(self, operation: str, destination: _Operand, source: _Operand) -> None:
        bits = self.width(destination)
        count = self.get(source) & (63 if bits == 64 else 31)
        value = self.get(destination)
        if not count:
            # Flags remain exactly as before; DWORD destination zero extension remains.
            self.put(destination, value)
            return
        if operation == "shl":
            result = value << count & _mask(bits)
            self.flags.carry = bool(value >> (bits - count) & 1) if count < bits else None
        elif operation == "shr":
            result = value >> count
            self.flags.carry = bool(value >> (count - 1) & 1) if count < bits else None
        else:
            result = _signed(value, bits // 8) >> count & _mask(bits)
            self.flags.carry = bool(value >> (min(count, bits) - 1) & 1)
        self.flags.zero, self.flags.sign = result == 0, bool(result & (1 << (bits - 1)))
        if count == 1:
            if operation == "shl":
                self.flags.overflow = self.flags.sign != self.flags.carry
            else:
                self.flags.overflow = bool(value >> (bits - 1)) if operation == "shr" else False
        else:
            self.flags.overflow = None
        self.put(destination, result)

    def multiply(self, operands: tuple[_Operand, ...], *, signed: bool) -> None:
        if signed:
            destination, source, immediate = operands
            bits = self.width(destination)
            left = _signed(self.get(source, bits=bits), bits // 8)
            right = _signed(self.get(immediate, bits=bits), bits // 8)
            product = left * right
            low = product & _mask(bits)
            overflow = product != _signed(low, bits // 8)
            self.put(destination, low)
        else:
            (source,) = operands
            bits = self.width(source)
            left = self.registers.read("rax", bits, self.site)
            product = left * self.get(source)
            low, high = product & _mask(bits), product >> bits
            self.registers.write("rax", bits, low)
            self.registers.write("rdx", bits, high)
            overflow = high != 0
        self.flags.carry = self.flags.overflow = overflow
        self.flags.zero = self.flags.sign = None

    def run(self, entry: int) -> int | None:
        pc = entry
        returns: list[int] = []
        while True:
            self.site = pc
            if pc == _EXIT:
                if returns or entry != _START:
                    raise UnresolvedReplayTaskRebuild("codec reached excluded physical epilogue")
                return self.registers.read("rax", 32, pc)
            instruction = _PROGRAM.get(pc)
            if instruction is None:
                raise UnresolvedReplayTaskRebuild(f"codec current control target{pc:x} unavailable")
            following, operation, operands = instruction
            pc = following
            if operation == "nop":
                continue
            if operation == "ret":
                if returns:
                    pc = returns.pop()
                    continue
                if entry != _HELPER:
                    raise UnresolvedReplayTaskRebuild("codec reached unbalanced helper return")
                return self.registers.return_rax()
            if operation in ("mov", "movabs", "movdqa", "movups", "movq"):
                destination, source = operands
                self.put(destination, self.get(source, bits=self.width(destination)))
            elif operation in ("movzx", "movsx", "movsxd"):
                destination, source = operands
                value = self.get(source)
                if operation != "movzx":
                    value = _signed(value, self.width(source) // 8)
                self.put(destination, value)
            elif operation == "lea":
                destination, source = operands
                self.put(destination, self.address(source))
            elif operation == "xorps":
                destination, source = operands
                if destination != source:
                    raise UnresolvedReplayTaskRebuild(
                        "codec only owns its source XORPS zero idioms"
                    )
                self.put(destination, 0)  # SSE zero idiom preserves arithmetic flags.
            elif operation in ("add", "sub", "cmp", "and", "or", "xor", "test"):
                destination, source = operands
                self.binary(operation, destination, source)
            elif operation in ("inc", "dec"):
                (destination,) = operands
                carry = self.flags.carry
                value = self.flags.arithmetic(
                    self.get(destination), 1, self.width(destination), subtract=operation == "dec"
                )
                self.flags.carry = carry
                self.put(destination, value)
            elif operation == "not":
                (destination,) = operands
                self.put(destination, ~self.get(destination))
            elif operation in ("shl", "shr", "sar"):
                destination, source = operands
                self.shift(operation, destination, source)
            elif operation in ("mul", "imul"):
                self.multiply(operands, signed=operation == "imul")
            elif operation == "cdqe":
                value = self.registers.read("rax", 32, self.site)
                self.registers.write("rax", 64, _signed(value, 4))
            elif operation == "bt":
                source, index = operands
                bits = self.width(source)
                self.flags.carry = bool(self.get(source) >> (self.get(index) % bits) & 1)
                self.flags.sign = self.flags.overflow = None
            elif operation.startswith("cmov"):
                destination, source = operands
                if self.flags.condition(operation[4:], self.site):
                    self.put(destination, self.get(source, bits=self.width(destination)))
                elif self.width(destination) == 32:
                    self.put(destination, self.get(destination))
            elif operation == "call":
                target = self.get(operands[0])
                if target == _HELPER:
                    returns.append(following)
                    pc = target
                elif target in _IATS:
                    self.imported(target)
                else:
                    raise UnresolvedReplayTaskRebuild(f"codec child{target:x} unprovided")
            elif operation == "jmp":
                target = self.get(operands[0])
                if target in _IATS:
                    returned = self.imported(target)
                    if returns:
                        pc = returns.pop()
                    elif entry == _HELPER:
                        return returned
                    else:
                        raise UnresolvedReplayTaskRebuild("codec reached unbalanced tail import")
                else:
                    pc = target
            elif operation.startswith("j"):
                if self.flags.condition(operation[1:], self.site):
                    pc = self.get(operands[0])
            else:
                raise UnresolvedReplayTaskRebuild(
                    f"codec{self.site:x} operation {operation} unprovided"
                )


def bind_replay_file_codec_homes(
    context: ReplayTaskRebuildStorage,
    calls: ReplayTaskRebuildCalls,
    *,
    imports: ReplayTaskRebuildCalls,
    bind_local: LocalBinding,
    profile: ReplayFileCodecProfile,
) -> ReplayTaskRebuildCalls:
    """Own complete inner/helper/thunks with a separate explicit live-HOME ABI.

    Main arguments are(state,input,inputCountQPtr,outBase,HOME5,HOME6,HOME7).
    The last3 are current engine addresses of outputCurrentQ,outputCountQPtrQ,
    flagsDWORD homes. Early HOME6 capture precedes HOME5 and count reads. All
    later flags/capacity samples remain individual current Storage reads.

    The full source instruction program owns all block types/resumptions,
    permissive tables, overlapping/ring copies, status/count/state ordering,
    unread bytes and optional header/checksum. No stdlib decoder is substituted.
    All current data tables and jump RVAs must be backed; code is immutable.
    No default tables/state/dictionary/flags/global initialization is supplied.

    Helper takes(state); thunks take three scalar args and transparently return
    imports results. Current IAT targets invoke mandatory imports capabilities,
    preserving coherent child Storage effects. Known child instruction effects
    are retained; external ABI-volatile values/flags become undefined except a
    supplied valid rawRAX. An ignored/opaque return is never eagerly validated.
    A later undefined source consumer refuses, retaining prior source effects.
    Win64 nonvolatile GPR preservation is the external capability ABI premise.

    The program is finite; original loops have no artificial dynamic step cap.
    Admit only terminating finite valid backing/child interactions. Physical
    prologue/cookie/save/return-stack identity, native faults/EH/concurrency and
    executable-code mutation are excluded. Logical locals remain live in one
    explicit180h seed through all synchronous child calls; escaped locals and
    physical adjacency to the three separately supplied homes are excluded.
    All admitted state/output/input/home/local aliases share current backing.
    Native undefined overlapping CRT-memcpy ranges are outside the capability
    profile unless separately established. This is not a prepared File/backend,
    outer568B decoder binding, stream readiness or observed runtime identity.
    """
    _validate(context, calls)
    _validate(context, imports)
    if not callable(bind_local) or not isinstance(profile, ReplayFileCodecProfile):
        raise ValueError("explicit codec local binding/profile required")

    def dispatch(target: int, args: tuple[int, ...], data: memoryview | None) -> int | None:
        arity = {_MAIN: 7, _HELPER: 1, _COPY: 3, _SET: 3}
        if target not in arity:
            if calls.call is None:
                raise UnresolvedReplayTaskRebuild(f"reached{target:x} is unavailable")
            return calls.call(target, args, data)
        if len(args) != arity[target] or data is not None:
            raise ValueError("malformed inner codec HOME/helper/thunk call")
        _validate(context, calls, *args)
        if target in _IATS:
            imported = _read(context, _IATS[target], 8)
            if imports.call is None:
                raise UnresolvedReplayTaskRebuild(f"codec import{imported:x} unavailable")
            return imports.call(imported, args, None)
        machine = _Machine(context, imports, args[4:] if target == _MAIN else ())
        registers = ("rcx", "rdx", "r8", "r9") if target == _MAIN else ("rcx",)
        for register, value in zip(registers, args, strict=False):
            machine.registers.write(register, 64, value)
        if target == _HELPER:
            return machine.run(_HELPER)
        with _local(memoryview(bytearray(profile.frame)), bind_local) as frame:
            machine.registers.write("rsp", 64, frame)
            machine.registers.write("rbp", 64, (frame + 0x100) & _U64)
            return machine.run(_START)

    return ReplayTaskRebuildCalls(dispatch)
